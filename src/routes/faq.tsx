function FaqPage() {
  const allFaqs = SECTIONS.flatMap(s => s.items);
  // JSON-LD لمحركات البحث
  const faqJsonLd = {
    "@context": "https://schema.org",
    "@type": "FAQPage",
    mainEntity: allFaqs.map(qa => ({
      "@type": "Question",
      name: qa.q,
      acceptedAnswer: { "@type": "Answer", text: qa.a + (qa.ref ? " — " + qa.ref : "") },
    })),
  };

  return (
    <div dir="rtl" className="container max-w-4xl mx-auto px-4 py-8 md:py-12 space-y-6">
      <script type="application/ld+json" dangerouslySetInnerHTML={{ __html: JSON.stringify(faqJsonLd) }} />

      <div className="flex items-center justify-between gap-3 flex-wrap">
        <div>
          <div className="flex items-center gap-2 mb-2">
            <Badge variant="outline" className="gap-1.5">
              <BookOpen className="h-3.5 w-3.5" /> مرجع علمي
            </Badge>
            <Badge variant="secondary">{allFaqs.length}+ سؤال</Badge>
          </div>
          <h1 className="text-2xl md:text-3xl font-bold flex items-center gap-2">
            <HelpCircle className="h-7 w-7 text-primary" />
            الأسئلة الشائعة عن الزكاة
          </h1>
          <p className="text-muted-foreground mt-2 text-sm md:text-base leading-relaxed">
            إجابات موثّقة بالأدلة الشرعية ومعايير AAOIFI ومخرجات المجامع الفقهية المعاصرة، مرتّبة في {SECTIONS.length} محاور تغطّي أبرز ما يحتاجه المزكّي اليوم.
          </p>
        </div>
        <Button asChild variant="outline" className="gap-2">
          <Link to="/">
            <ArrowRight className="h-4 w-4" />
            العودة إلى الحاسبة
          </Link>
        </Button>
      </div>

      {SECTIONS.map((section, idx) => (
        <Card key={idx} className="shadow-soft">
          <CardHeader>
            <CardTitle className="text-lg md:text-xl flex items-center gap-2">
              <span className="text-primary">{String(idx + 1).padStart(2, "0")}</span>
              {section.title}
              <Badge variant="outline" className="ms-auto">{section.items.length}</Badge>
            </CardTitle>
          </CardHeader>
          <CardContent>
            <Accordion type="multiple" className="space-y-2">
              {section.items.map((qa, i) => (
                <AccordionItem
                  key={i}
                  value={`s${idx}-q${i}`}
                  className="border rounded-lg px-4 bg-muted/30"
                >
                  <AccordionTrigger className="text-right hover:no-underline font-semibold py-3">
                    {qa.q}
                  </AccordionTrigger>
                  <AccordionContent className="text-sm md:text-base leading-relaxed space-y-2 pb-4">
                    <p>{qa.a}</p>
                    {qa.ref && (
                      <p className="text-xs text-muted-foreground border-r-2 border-primary/40 pr-3 italic">
                        المرجع: {qa.ref}
                      </p>
                    )}
                  </AccordionContent>
                </AccordionItem>
              ))}
            </Accordion>
          </CardContent>
        </Card>
      ))}

      <Card className="bg-primary/5 border-primary/20">
        <CardContent className="pt-6 text-center space-y-3">
          <p className="text-sm text-muted-foreground">
            تنبيه: هذه الإجابات للتعريف والإرشاد العام، ولا تُغني عن استشارة المتخصصين في الحالات الخاصة والمركّبة.
          </p>
          <Button asChild>
            <Link to="/advisor">استشر المستشار الذكي للزكاة</Link>
          </Button>
        </CardContent>
      </Card>
    </div>
  );
}
